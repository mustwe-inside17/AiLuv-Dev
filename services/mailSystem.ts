/**
 * Deliver a mail to the player's inbox with optional toast notification and SFX
 */
export function deliverMail(mail: MailItem, options: { showToast?: boolean; playSound?: boolean } = { showToast: true, playSound: true }): boolean {
    const store = useGameStore.getState();
    const existingMails = store.mails || [];

    // Check if mail already exists
    if (existingMails.some(m => m.id === mail.id)) {
        return false;
    }

    // Add to store
    store.addMail(mail);

    // Play SFX
    if (options.playSound) {
        try {
            playSfx('chat_receive');
        } catch {
            // Ignore sound errors if not ready
        }
    }

    // Show Notification Toast
    if (options.showToast) {
        const rewardSummary: string[] = [];
        if (mail.rewards?.gold) rewardSummary.push(`+${mail.rewards.gold} G`);
        if (mail.rewards?.diamonds) rewardSummary.push(`+${mail.rewards.diamonds} Gems`);
        if (mail.rewards?.item) rewardSummary.push('🎁 Item');

        useUIStore.getState().addNotification({
            id: `toast_${mail.id}_${Date.now()}`,
            title: `📧 จดหมายใหม่: ${mail.sender}`,
            message: mail.subject,
            type: mail.type === 'secret' ? 'critical' : 'event',
            rewards: rewardSummary.length > 0 ? rewardSummary : undefined,
            actionLabel: 'เปิดอ่าน',
            onAction: () => {
                useGameStore.getState().openPhone('mail');
            }
        });
    }

    return true;
}

/**
 * Check and ensure starter mails exist (Delivered only once per citizen lifetime)
 */
export function checkAndDeliverStarterMails(): void {
    const store = useGameStore.getState();

    // If the player has already received starter mails in their lifetime, never deliver again
    if (store.hasReceivedStarterMails) {
        return;
    }

    const existingMails = store.mails || [];

    // Check if legacy user already has any welcome starter mail
    const hasLegacyStarter = existingMails.some(m => 
        m.id === 'mail_welcome_citizen' || m.id === 'mail_welcome' || m.id === 'mail_city_handbook'
    );

    if (hasLegacyStarter) {
        // Stamp flag so it never checks again
        store.setGameState({ hasReceivedStarterMails: true });
        return;
    }

    STARTER_MAILS.forEach(starter => {
        if (!existingMails.some(m => m.id === starter.id)) {
            deliverMail(starter, { showToast: false, playSound: false });
        }
    });

    // Mark permanently as received
    store.setGameState({ hasReceivedStarterMails: true });
}

/**
 * Daily News Delivery: Checks if player received today's newspaper
 */
export function checkAndDeliverDailyNews(force: boolean = false): boolean {
    const store = useGameStore.getState();
    const todayStr = new Date().toDateString();
    const existingMails = store.mails || [];

    // Check if daily news was already delivered today
    const newsIdToday = `daily_news_${todayStr.replace(/\s+/g, '_')}`;
    if (!force && existingMails.some(m => m.id === newsIdToday)) {
        return false;
    }

    // Pick random news from DAILY_NEWS_POOL
    const pool = DAILY_NEWS_POOL && DAILY_NEWS_POOL.length > 0 ? DAILY_NEWS_POOL : [
        {
            sender: 'AiLuv Daily News',
            subject: 'สภาพอากาศและบรรยากาศในเมืองวันนี้แจ่มใสเป็นพิเศษ ☀️',
            body: 'กรมอุตุนิยมวิทยา AiLuv City รายงานสภาพอากาศสดใส เหมาะแก่การออกไปเดินเล่นที่ Central Park หรือจิบกาแฟที่ Cafe Amor ค่าพลังงานและอารมณ์ของทุกคนพร้อมรับวันใหม่!'
        }
    ];

    const randomNews = pool[Math.floor(Math.random() * pool.length)];

    const dailyMail: MailItem = {
        id: newsIdToday,
        sender: randomNews.sender,
        subject: `[หนังสือพิมพ์] ${randomNews.subject}`,
        body: `${randomNews.body}\n\n📰 ทางสำนักข่าว AiLuv Daily ขอมอบเบี้ยเลี้ยงค่าอ่านข่าวประจำวันให้คุณ 50 Gold และ 10 Diamonds ขอให้วันนี้เป็นวันที่ดี!`,
        timestamp: Date.now(),
        isRead: false,
        type: 'system',
        rewards: {
            gold: 50,
            diamonds: 10
        },
        isClaimed: false
    };

    return deliverMail(dailyMail, { showToast: true, playSound: true });
}

/**
 * Secret Dilemma / Story Mail Delivery
 */
export function checkAndDeliverSecretMail(force: boolean = false): boolean {
    const store = useGameStore.getState();
    const existingMails = store.mails || [];

    // Filter scenarios that haven't been received yet
    const availableScenarios = SECRET_MAIL_SCENARIOS.filter(
        scenario => !existingMails.some(m => m.id.startsWith(`secret_${scenario.id}`))
    );

    if (availableScenarios.length === 0 && !force) {
        return false;
    }

    const pool = availableScenarios.length > 0 ? availableScenarios : SECRET_MAIL_SCENARIOS;
    const scenario = pool[Math.floor(Math.random() * pool.length)];
    const timestamp = Date.now();

    const secretMail: MailItem = {
        id: `secret_${scenario.id}_${timestamp}`,
        sender: scenario.sender,
        subject: `🔒 [จดหมายลับ] ${scenario.subject}`,
        body: scenario.body,
        timestamp: timestamp,
        isRead: false,
        type: 'secret',
        actions: [
            {
                id: `act_A_${timestamp}`,
                label: scenario.choices[0].label,
                type: 'REPLY',
                payload: `${scenario.id}:0`,
                style: scenario.choices[0].style
            },
            {
                id: `act_B_${timestamp}`,
                label: scenario.choices[1].label,
                type: 'REPLY',
                payload: `${scenario.id}:1`,
                style: scenario.choices[1].style
            }
        ]
    };

    return deliverMail(secretMail, { showToast: true, playSound: true });
}

