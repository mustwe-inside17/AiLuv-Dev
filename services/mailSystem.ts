/**
 * Character Relationship Milestone Mail
 * Sends a personalized letter when the player reaches a new tier with a character
 */
export function sendCharacterMilestoneMail(charId: CharacterId, tier: RelationshipTier): boolean {
    const char = CHARACTER_DATA[charId];
    if (!char) return false;

    const charName = char.name;
    const mailId = `milestone_${charId}_${tier}`;

    // Lookup tailored template for this specific character & tier
    const charTemplates = CHARACTER_MILESTONE_TEMPLATES[charId];
    const template = charTemplates ? charTemplates[tier] : undefined;

    let subject = '';
    let body = '';
    let gold = 150;
    let item: string | undefined = undefined;

    if (template) {
        subject = template.subject;
        body = template.body;
        gold = template.gold;
        item = template.item;
    } else {
        // Fallback for custom tiers
        subject = `ความผูกพันระดับใหม่กับ ${charName} ✨`;
        body = `สวัสดีครับ/ค่ะ!\n\nขอบคุณมากที่ร่วมแบ่งปันช่วงเวลาดีๆ ร่วมกันนะ ระดับความสัมพันธ์ของเราขยับขึ้นสู่ขั้น ${tier} แล้ว ขอบคุณที่อยู่เคียงข้างกันเสมอนะครับ/ค่ะ!\n\n— ${charName}`;
        gold = 200;
        item = 'food_cookie';
    }

    const milestoneMail: MailItem = {
        id: mailId,
        sender: charName,
        subject: `💌 ${subject}`,
        body: body,
        timestamp: Date.now(),
        isRead: false,
        type: 'personal',
        rewards: {
            gold,
            item
            // Note: NO diamonds in milestone mails as requested
        },
        isClaimed: false
    };

    return deliverMail(milestoneMail, { showToast: true, playSound: true });
}

